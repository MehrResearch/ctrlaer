#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Build the API reference from actual signatures/docstrings without RP2 imports.

Run ``uv run tools/build_api.py`` after editing public docstrings, or append
``--check`` to fail if the checked-in reference differs. Missing public
docstrings fail the build instead of silently producing an incomplete reference.
"""
import argparse
import ast
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
SECTIONS = [
    ('Signal commands', 'ctrlaer_commands', ['pulse','chirp','sleep','print','wait_for']),
    ('Composition', 'ctrlaer', ['mux']),
    ('Analysis and compiled programs', 'ctrlaer_program', ['Trigger','compile_program','CompiledProgram']),
    ('Controller and groups', 'ctrlaer', ['CtrlAer','Group']),
    ('Prepared runs', 'ctrlaer_runtime', ['PreparedRun','PreparedGroup']),
    ('Buffered runs', 'ctrlaer_buffered', ['BufferedRun']),
    ('Digital capture', 'ctrlaer_capture', ['DigitalCapture','Trace','CaptureOverrunError']),
    ('Execution errors', 'ctrlaer_runtime', ['UnderrunError','ExecutionTimeoutError','GateTimeoutError']),
    ('Desktop analysis', 'ctrlaer_tools', ['parameter_scan','render_svg','program_to_dict','program_from_dict']),
    ('Experiment records', 'ctrlaer_records', ['save_record','load_record','fingerprint','device_info']),
]


def signature(node, qualified=None):
    arguments = ast.unparse(node.args)
    if arguments in ('self','cls'):
        arguments = ''
    elif arguments.startswith(('self, ','cls, ')):
        arguments = arguments.split(', ',1)[1]
    return f'{qualified or node.name}({arguments})'


def build():
    modules = {}
    for _, module, _ in SECTIONS:
        if module not in modules:
            tree = ast.parse((ROOT / (module + '.py')).read_text())
            modules[module] = {node.name:node for node in tree.body
                               if isinstance(node,(ast.FunctionDef,ast.ClassDef))}
    output = [
        '# API reference',
        '<!-- Generated by tools/build_api.py. Edit the corresponding Python docstrings. -->',
        'This reference uses the signatures and docstrings in this checkout. '
        'Device execution requires MicroPython; analysis, previews and records '
        'can also be used on desktop Python. See [execution modes](execution-modes.md) '
        'for the timing and ordering guarantees of each mode.',
        '## Constants',
        '| Name | Value | Meaning on one channel |\n|---|---|---|\n'
        '| `LOW`, `OFF`, `PULSE00` | `0b00` | Both half cycles LOW |\n'
        '| `PULSE01` | `0b01` | First half HIGH, second half LOW |\n'
        '| `ON`, `PULSE10` | `0b10` | First half LOW, second half HIGH |\n'
        '| `HIGH`, `PULSE11` | `0b11` | Both half cycles HIGH |\n'
        '| `FREQ` | `108050` Hz | Default controller/analysis carrier frequency |\n'
        '| `RP_CLK` | Device clock in Hz, or `None` on desktop | Clock at import time; a later clock change does not update this constant |',
        'The integer states use two bit planes when combined with `mux()`. '
        '`pulse()`/`chirp()` specify their own carrier settings. Durations use '
        'milliseconds by default; `use_ms=False` uses periods of the controller '
        'or analysis `freq`, including for rich commands.',
    ]
    missing = []
    output.append('## Predefined generator instances')
    for name in ('always_on','inactive'):
        doc = ast.get_docstring(modules['ctrlaer']['_' + name])
        if not doc:
            missing.append(name)
        output.append('### `' + name + '`')
        output.append(doc or '')

    def document(node, name, depth):
        doc = ast.get_docstring(node)
        if not doc:
            missing.append(name)
        output.append('#' * depth + ' ' + f'`{name}`')
        if isinstance(node,ast.FunctionDef):
            property_node = any(isinstance(decorator,ast.Name) and decorator.id=='property'
                                for decorator in node.decorator_list)
            label = name if property_node else signature(node,name)
            output.append('```python\n' + label + '\n```')
        else:
            constructors = [member for member in node.body if isinstance(member,ast.FunctionDef)
                            and member.name in ('__init__','__new__')]
            if constructors:
                output.append('```python\n' + signature(constructors[0],name) + '\n```')
        output.append(doc or '')
        if isinstance(node,ast.ClassDef):
            for member in node.body:
                if not isinstance(member,ast.FunctionDef) or member.name.startswith('_'):
                    continue
                if any(isinstance(decorator,ast.Attribute) and decorator.attr=='setter'
                       for decorator in member.decorator_list):
                    continue
                document(member,name+'.'+member.name,depth+1)
            if any(isinstance(base,ast.Name) and base.id=='PreparedRun' for base in node.bases):
                output.append('Other lifecycle methods and properties are inherited from '
                              '[`PreparedRun`](#preparedrun).')

    for title,module,names in SECTIONS:
        output.append('## ' + title)
        output.append(f'Source: `{module}.py`.')
        for name in names:
            document(modules[module][name],name,3)
    if missing:
        raise ValueError('Missing public docstrings:\n  ' + '\n  '.join(missing))
    return '\n\n'.join(output) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    try:
        generated = build()
    except (KeyError,ValueError) as error:
        parser.exit(1,str(error)+'\n')
    target = ROOT / 'docs/api-reference.md'
    if args.check:
        if not target.exists() or target.read_text()!=generated:
            parser.exit(1,'API reference is stale; run uv run tools/build_api.py\n')
        print('API signatures and docstrings match the reference.')
    else:
        target.write_text(generated)
        print('Updated docs/api-reference.md from source docstrings.')


if __name__=='__main__':
    main()
